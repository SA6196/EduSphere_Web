-- Safe READ-ONLY verification; can run after fresh install OR on existing schema.
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE
PROMPT Current container, schema and object counts:
SELECT USER AS OWNER_NAME, SYS_CONTEXT('USERENV','CON_NAME') AS CONTAINER_NAME FROM DUAL;
SELECT OBJECT_TYPE, STATUS, COUNT(*) AS OBJECT_COUNT
  FROM USER_OBJECTS WHERE OBJECT_TYPE IN ('TABLE','FUNCTION','PROCEDURE','TRIGGER')
  GROUP BY OBJECT_TYPE, STATUS ORDER BY OBJECT_TYPE, STATUS;
SELECT NAME, TYPE, LINE, TEXT FROM USER_ERRORS
  WHERE TYPE IN ('FUNCTION','PROCEDURE','TRIGGER') ORDER BY NAME, SEQUENCE;
DECLARE
  v_count NUMBER;
  v_invalid NUMBER;
  v_core NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES;
  IF v_count <> 37 THEN
    RAISE_APPLICATION_ERROR(-20664, 'Expected exactly 37 tables; found '||v_count);
  END IF;
  SELECT COUNT(*) INTO v_invalid FROM USER_OBJECTS
    WHERE STATUS='INVALID' AND OBJECT_TYPE IN ('FUNCTION','PROCEDURE','TRIGGER');
  IF v_invalid > 0 THEN
    RAISE_APPLICATION_ERROR(-20665, 'Invalid PL/SQL objects: '||v_invalid);
  END IF;
  SELECT COUNT(*) INTO v_core FROM USER_OBJECTS
    WHERE OBJECT_TYPE IN ('PROCEDURE','TRIGGER') AND STATUS='VALID'
      AND OBJECT_NAME IN ('PR_SUBMIT_QUIZ_ATTEMPT','TRG_QUIZ_ATTEMPT');
  IF v_core <> 2 THEN
    RAISE_APPLICATION_ERROR(-20666, 'Timeout procedure/trigger not valid.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('PASS: 37 tables, no invalid PL/SQL, quiz timeout objects valid.');
END;
