-- Execute ONLY as privileged SYS/SYSTEM connected to a NEW PDB (XEPDB1), not CDB$ROOT.
-- SQL*Plus/SQLcl interactive script. Prompts for independent user passwords.
-- This does not create or modify application tables.
SET ECHO OFF
SET VERIFY OFF
SET DEFINE ON
SET SERVEROUTPUT ON
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
  v_pdb VARCHAR2(128);
BEGIN
  v_pdb := SYS_CONTEXT('USERENV','CON_NAME');
  IF v_pdb = 'CDB$ROOT' THEN
    RAISE_APPLICATION_ERROR(-20660, 'Connect to XEPDB1; do not run in CDB$ROOT.');
  END IF;
END;
/
ACCEPT ed_owner_pwd CHAR PROMPT 'New EDUSPHERE_OWNER password: ' HIDE
ACCEPT ed_app_pwd CHAR PROMPT 'New EDUSPHERE_APP password: ' HIDE
CREATE USER EDUSPHERE_OWNER IDENTIFIED BY "&ed_owner_pwd"
  DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE, CREATE SYNONYM
  TO EDUSPHERE_OWNER;
CREATE USER EDUSPHERE_APP IDENTIFIED BY "&ed_app_pwd"
  DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP;
GRANT CREATE SESSION TO EDUSPHERE_APP;
UNDEFINE ed_owner_pwd
UNDEFINE ed_app_pwd
PROMPT Database users created. Reconnect as EDUSPHERE_OWNER to run 01_FINAL_FRESH_INSTALL.sql.
