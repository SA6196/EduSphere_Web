-- EduSphere 2026 backend-compliance runtime grants; run as EDUSPHERE_OWNER.
-- Does NOT change the fixed 37-table schema or any saved student data.
-- Apply only after reviewing least-privilege requirements of the Django service.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
    v_user VARCHAR2(128);
BEGIN
    SELECT USER INTO v_user FROM DUAL;
    IF v_user <> 'EDUSPHERE_OWNER' THEN
        RAISE_APPLICATION_ERROR(-20581, 'This grant delta must run as EDUSPHERE_OWNER.');
    END IF;
    IF SYS_CONTEXT('USERENV','CON_NAME') = 'CDB$ROOT' THEN
        RAISE_APPLICATION_ERROR(-20582, 'Connect to XEPDB1, not CDB$ROOT.');
    END IF;
END;
/

