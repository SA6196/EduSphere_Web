    Recorded_By_User_ID NUMBER NOT NULL,
    Recorded_At TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    Graded_Submission_ID NUMBER,
    CONSTRAINT PK_STUDENT_MARK PRIMARY KEY (Mark_ID),
    CONSTRAINT FK_MARK_COMPONENT FOREIGN KEY (Component_ID) REFERENCES ASSESSMENT_COMPONENT (Component_ID),
    CONSTRAINT FK_MARK_ENROLLMENT FOREIGN KEY (Enrollment_ID) REFERENCES ENROLLMENT (Enrollment_ID),
    CONSTRAINT FK_MARK_USER FOREIGN KEY (Recorded_By_User_ID) REFERENCES LMS_USER (User_ID),
    CONSTRAINT FK_MARK_SUBMISSION FOREIGN KEY (Graded_Submission_ID) REFERENCES ASSIGNMENT_SUBMISSION (Submission_ID),
    CONSTRAINT UQ_STUDENT_MARK UNIQUE (Component_ID, Enrollment_ID),
    CONSTRAINT CK_MARK_NONNEG CHECK (Marks_Obtained >= 0)
);

